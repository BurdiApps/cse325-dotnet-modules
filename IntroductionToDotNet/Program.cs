using System; // Makes System namespace types available (ex: Console)

// A class is a container for related code (methods, fields, etc.).
public class Program
{
    // Main is the application entry point.
    // The .NET runtime starts execution here.
    public static void Main()
    {
        // Console is a class in the System namespace.
        // WriteLine is a method on Console.
        // "Hello world!" is a string literal.
        Console.WriteLine("Hello world!"); // Prints text and adds a new line.
    }
}